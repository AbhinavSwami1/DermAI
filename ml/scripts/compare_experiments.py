"""Collect experiment results into docs/EXPERIMENT_RESULTS.md and evaluate ensembles.

  python ml/scripts/compare_experiments.py
  python ml/scripts/compare_experiments.py --ensemble convnext_tiny_lr1e-4 mnv3_lr1e-4 [--with-test]
Ensemble = mean of softmax probabilities. Test is used only with --with-test, and only
for runs trained with --eval-test.
"""
import argparse
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import balanced_accuracy_score, f1_score

ML_ROOT = Path(__file__).resolve().parents[1]
EXP = ML_ROOT / "outputs" / "experiments"


def softmax(z):
    z = z - z.max(1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(1, keepdims=True)


def m(logits_or_probs, y):
    p = logits_or_probs.argmax(1)
    return (float((p == y).mean()), float(balanced_accuracy_score(y, p)), float(f1_score(y, p, average="macro", zero_division=0)))


def fmt(x):
    return "-" if x is None else f"{x * 100:.2f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ensemble", nargs="+")
    ap.add_argument("--with-test", action="store_true")
    args = ap.parse_args()

    rows = []
    for d in sorted(EXP.glob("*/")):
        v = d / "val_metrics.json"
        if not v.exists():
            continue
        cfg = json.loads((d / "config.json").read_text())
        vm = json.loads(v.read_text())
        t = json.loads((d / "test_metrics.json").read_text()) if (d / "test_metrics.json").exists() else None
        rows.append((d.name, cfg, vm, t))

    lines = ["# Experiment Results", "",
             "Generated by `ml/scripts/compare_experiments.py`. Selection uses validation; test values appear only for runs evaluated once with `--eval-test`.", "",
             "| Run | Arch | LR | Trainable | Params (trainable/total) | Best epoch | Val acc | Val bal. acc | Val macro F1 | Test acc | Test macro F1 | Inference ms/img | Train s |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, cfg, vm, t in rows:
        lines.append(f"| {name} | {cfg['arch']} | {cfg['lr']:g} | {cfg['trainable']} | {cfg['trainable_params']:,}/{cfg['total_params']:,} | "
                     f"{vm['best_epoch']} | {fmt(vm['accuracy'])} | {fmt(vm['balanced_accuracy'])} | {fmt(vm['macro_f1'])} | "
                     f"{fmt(t['accuracy']) if t else '-'} | {fmt(t['macro_f1']) if t else '-'} | {vm['inference_ms_per_image']:.1f} | {vm['train_seconds']:.0f} |")

    if args.ensemble:
        vp = [softmax(np.load(EXP / r / "val_logits.npy")) for r in args.ensemble]
        vy = np.load(EXP / args.ensemble[0] / "val_labels.npy")
        va, vb, vf = m(np.mean(vp, 0), vy)
        line = f"| ensemble({'+'.join(args.ensemble)}) | mean softmax | - | - | - | - | {fmt(va)} | {fmt(vb)} | {fmt(vf)} | "
        if args.with_test:
            tp = [softmax(np.load(EXP / r / "test_logits.npy")) for r in args.ensemble]
            ty = np.load(EXP / args.ensemble[0] / "test_labels.npy")
            ta, _, tf = m(np.mean(tp, 0), ty)
            line += f"{fmt(ta)} | {fmt(tf)} | - | - |"
        else:
            line += "- | - | - | - |"
        lines += ["", "## Ensemble", "", lines[4].replace(lines[4], lines[3]), lines[4], line]

    out = ML_ROOT.parent / "docs" / "EXPERIMENT_RESULTS.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
